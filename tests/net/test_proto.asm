; clear g_pw, no packet id
%macro PW_RESET 0.nolist
    xor  ecx, ecx
    call pw_begin
    lea  rax, [rel g_pw]
    mov  dword [rax+PKTW.len], 0
%endmacro

; g_pw holds exactly the bytes at label
%macro CHECK_PW 2.nolist
    lea  rax, [rel g_pw]
    mov  ebx, [rax+PKTW.len]
    CHECK_EQ32 ebx, %1_len, %2
    lea  rax, [rel g_pw]
    mov  rbx, [rax+PKTW.buf]
    lea  rsi, [rel %1]
    CHECK_MEM rbx, rsi, %1_len, %2
%endmacro

; reader over label
%macro RD 1.nolist
    lea  rcx, [rel rd]
    lea  rdx, [rel %1]
    mov  r8d, %1_len
    call pr_init
%endmacro

%macro CHECK_RD_DONE 1.nolist
    call rd_done
    mov  ebx, eax
    CHECK_TRUE ebx, %1
%endmacro

%macro VI 2.nolist
    PW_RESET
    mov  ecx, %1
    call pw_varint
    CHECK_PW %2, "varint encode"
    RD %2
    lea  rcx, [rel rd]
    call pr_varint
    mov  ebx, eax
    CHECK_EQ32 ebx, %1, "varint decode"
    CHECK_RD_DONE "varint consumed exactly"
%endmacro

%macro VL 2.nolist
    PW_RESET
    mov  rcx, %1
    call pw_varlong
    CHECK_PW %2, "varlong encode"
    RD %2
    lea  rcx, [rel rd]
    call pr_varlong
    mov  rbx, rax
    mov  rsi, %1
    CHECK_EQ rbx, rsi, "varlong decode"
    CHECK_RD_DONE "varlong consumed exactly"
%endmacro

%macro POS 4.nolist
    PW_RESET
    mov  ecx, %1
    mov  edx, %2
    mov  r8d, %3
    call pw_position
    CHECK_PW %4, "position encode"
    RD %4
    lea  rcx, [rel rd]
    lea  rdx, [rel ibuf]
    call pr_position
    lea  rax, [rel ibuf]
    mov  ebx, [rax]
    CHECK_EQ32 ebx, %1, "position decode x"
    lea  rax, [rel ibuf]
    mov  ebx, [rax+4]
    CHECK_EQ32 ebx, %2, "position decode y"
    lea  rax, [rel ibuf]
    mov  ebx, [rax+8]
    CHECK_EQ32 ebx, %3, "position decode z"
%endmacro

%macro MD5 1.nolist
    lea  rcx, [rel md5_in%1]
    mov  edx, md5_in%1_len
    lea  r8, [rel obuf]
    call mcproto_md5
    lea  rbx, [rel obuf]
    lea  rsi, [rel md5_out%1]
    CHECK_MEM rbx, rsi, 16, "md5 vector"
%endmacro

