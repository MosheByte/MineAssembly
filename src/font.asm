; bit 7 = leftmost column, short strings get zero padded
%macro FROW 1
    %strlen %%len %1
    %assign %%v 0
    %assign %%i 1
    %rep 8
        %assign %%v (%%v << 1)
        %if %%i <= %%len
            %substr %%c %1 %%i
            %ifidn %%c, '#'
                %assign %%v (%%v | 1)
            %endif
        %endif
        %assign %%i (%%i + 1)
    %endrep
    db %%v
%endmacro

; a negative `times` error from nasm means the codes are out of order
%macro GLYPH 9
    times ((%1) * 8 - ($ - font_bits)) db 0
    FROW %2
    FROW %3
    FROW %4
    FROW %5
    FROW %6
    FROW %7
    FROW %8
    FROW %9
%endmacro

